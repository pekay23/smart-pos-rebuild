SELECT format('CREATE ROLE pos_api_expiry_worker NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='pos_api_expiry_worker')
\gexec

SELECT format('CREATE ROLE pos_api_expiry_runner LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS', :'runner_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='pos_api_expiry_runner')
\gexec

ALTER ROLE pos_api_expiry_worker NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
ALTER ROLE pos_api_expiry_runner LOGIN PASSWORD :'runner_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
GRANT CONNECT ON DATABASE advanced_pos TO pos_api_expiry_runner;
GRANT USAGE ON SCHEMA public TO pos_api_expiry_worker;
REVOKE CREATE ON SCHEMA public FROM pos_api_expiry_runner;
REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM pos_api_expiry_runner;
REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM pos_api_expiry_runner;
